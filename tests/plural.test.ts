/** Русские формы слова по числу (подписи «12 сроков», «1 срок»). Чистая функция. */
import { describe, expect, it } from 'vitest';
import { plural } from '../src/domain/plural';

describe('plural', () => {
  it('единица, двойка и много', () => {
    expect(plural(1, 'срок', 'срока', 'сроков')).toBe('срок');
    expect(plural(2, 'срок', 'срока', 'сроков')).toBe('срока');
    expect(plural(5, 'срок', 'срока', 'сроков')).toBe('сроков');
    expect(plural(0, 'срок', 'срока', 'сроков')).toBe('сроков');
  });

  it('исключения 11–14', () => {
    expect(plural(11, 'срок', 'срока', 'сроков')).toBe('сроков');
    expect(plural(12, 'срок', 'срока', 'сроков')).toBe('сроков');
    expect(plural(14, 'срок', 'срока', 'сроков')).toBe('сроков');
    expect(plural(112, 'срок', 'срока', 'сроков')).toBe('сроков');
  });

  it('составные числа 21, 22, 25', () => {
    expect(plural(21, 'срок', 'срока', 'сроков')).toBe('срок');
    expect(plural(22, 'срок', 'срока', 'сроков')).toBe('срока');
    expect(plural(25, 'срок', 'срока', 'сроков')).toBe('сроков');
  });
});
